package io.github.indexsmith.generator.generate;

import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.Modifier;
import com.github.javaparser.ast.PackageDeclaration;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.body.ConstructorDeclaration;
import com.github.javaparser.ast.body.EnumDeclaration;
import com.github.javaparser.ast.comments.BlockComment;
import com.github.javaparser.ast.expr.AssignExpr;
import com.github.javaparser.ast.expr.FieldAccessExpr;
import com.github.javaparser.ast.expr.Name;
import com.github.javaparser.ast.expr.NameExpr;
import com.github.javaparser.ast.expr.ThisExpr;
import com.github.javaparser.ast.stmt.BlockStmt;
import com.github.javaparser.ast.stmt.ExpressionStmt;
import io.github.indexsmith.generator.builder.BlockCommentBuilder;
import java.util.Map;

/**
 */
public abstract class BaseJavaAstGenerator {

    protected BlockComment getJavaClassComment() {
        return BlockCommentBuilder.builder()
                .addComment("Generated by indexsmith. Do not edit manually.")
                .build();
    }

    /**
     * 根据索引名称获取类名
     * @param indexName 索引名
     * @return 类名
     */
    protected abstract String getClassName(String indexName);

    protected CompilationUnit buildCompilationUnit(Name packageName) {
        CompilationUnit compilationUnit = new CompilationUnit();
        PackageDeclaration packageDeclaration = new PackageDeclaration(packageName);
        compilationUnit.setPackageDeclaration(packageDeclaration);
        return compilationUnit;
    }

    protected ClassOrInterfaceDeclaration buildClass(String className, CompilationUnit compilationUnit) {
        ClassOrInterfaceDeclaration classDeclaration = compilationUnit.addClass(className, Modifier.Keyword.PUBLIC);
        classDeclaration.setComment(getJavaClassComment());
        return classDeclaration;
    }

    protected EnumDeclaration buildEnum(String className, CompilationUnit compilationUnit, Map<String,Class<?>> fields) {
        EnumDeclaration enumDeclaration = compilationUnit.addEnum(className, Modifier.Keyword.PUBLIC);
        enumDeclaration.setComment(getJavaClassComment());
        ConstructorDeclaration constructorDeclaration = enumDeclaration.addConstructor(Modifier.Keyword.PRIVATE)
                .setBody(new BlockStmt());
        fields.forEach((fieldName, aClassType) -> {
            enumDeclaration.addPrivateField(aClassType, fieldName).createGetter();
            constructorDeclaration.addAndGetParameter(aClassType, fieldName);
            constructorDeclaration.getBody().addStatement(getSignStatement(fieldName, fieldName));
        });
        return enumDeclaration;
    }

    private ExpressionStmt getSignStatement(String left, String right) {
        return new ExpressionStmt(new AssignExpr(
                new FieldAccessExpr(new ThisExpr(), left),
                new NameExpr(right),
                AssignExpr.Operator.ASSIGN));
    }

}
